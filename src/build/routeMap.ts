import { existsSync } from 'node:fs';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import type { BuildConfig } from '../../types/build';
import { scanFileRoutes } from './fileRoutes';

/* The project's routes as types, so `route('/blog/:slug', { slug })` can
 * be checked before anything is built — the same arrangement as the
 * manifest keys (build/manifestKeys.ts), from the same scan the build
 * itself uses.
 *
 * The keys are TYPED paths, not registered ones: `[...rest]` registers as
 * `/docs/*` and is typed `/docs/:rest`, and an `[[optional]]` segment is
 * typed `:lang?`. That is what a caller writes and what names the params,
 * and `routesFromFile` already computes it (`typePath`) for exactly this
 * reason.
 *
 * An `[[optional]]` route serves two paths from one file and one
 * `typePath` covers both, so the map has one key for it. Deduplicated
 * because several registered paths can share a typed one. */

/** Where the declaration is written, relative to the project root. */
export const ROUTE_MAP_DECLARATION = '.absolutejs/types/routes.d.ts';

const PACKAGE = '@absolutejs/absolute';

/** The typed paths of a project's file routes, sorted and deduplicated. */
export const deriveRoutePaths = (
	config: BuildConfig,
	projectRoot = process.cwd()
) => {
	const { routes } = scanFileRoutes(config, projectRoot);

	return [
		...new Set(routes.map((entry) => entry.typePath ?? entry.path))
	].sort();
};

/** The declaration that types `route()`: it adds every path to the
 *  package's `AbsoluteRouteMap` interface. */
export const routeMapDeclarationSource = (paths: readonly string[]) => {
	const members = paths.map((path) => `\t\t${JSON.stringify(path)}: true;`);

	return `// Generated by AbsoluteJS from the project's file routes
// (absolute dev, absolute build, absolute typecheck). Do not edit.
export {};

declare module '${PACKAGE}' {
	interface AbsoluteRouteMap {
${members.join('\n')}
	}
}
`;
};

/** Derives the project's routes and writes the declaration, unless it
 *  already says exactly that (an unchanged file keeps its mtime, so
 *  editors and watchers see nothing). Several configs sharing a project
 *  root get one declaration with all their routes.
 *
 *  A project with no file routes gets no declaration, so `route()`
 *  accepts any path there — which is what makes it usable before
 *  `fileRoutes` is turned on, and what stops this from being a breaking
 *  change for every existing app.
 *
 *  Never throws: a project the scan cannot read keeps the declaration it
 *  had, because failing a build over a link type would be worse than
 *  checking links against a slightly stale map.
 *
 *  Returns the declaration's path when one exists afterwards. */
export const writeRouteMapDeclaration = async (
	configs: BuildConfig | BuildConfig[],
	projectRoot = process.cwd()
) => {
	const path = join(projectRoot, ROUTE_MAP_DECLARATION);
	try {
		const paths = [
			...new Set(
				(Array.isArray(configs) ? configs : [configs]).flatMap(
					(config) => deriveRoutePaths(config, projectRoot)
				)
			)
		].sort();
		if (paths.length === 0) await rm(path, { force: true });
		if (paths.length === 0) return null;
		const source = routeMapDeclarationSource(paths);
		const current = existsSync(path)
			? await readFile(path, 'utf-8')
			: undefined;
		if (current === source) return path;
		await mkdir(dirname(path), { recursive: true });
		const staging = `${path}.${process.pid}.tmp`;
		await writeFile(staging, source);
		await rename(staging, path);

		return path;
	} catch {
		return existsSync(path) ? path : null;
	}
};
