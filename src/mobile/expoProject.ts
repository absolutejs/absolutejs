export const writeAbsoluteExpoProject = async (
	config: NormalizedAbsoluteMobileConfig,
	options: WriteAbsoluteExpoProjectOptions
) => {
	if (config.engine !== 'expo')
		throw new TypeError(
			'Expo project generation requires mobile.engine: expo.'
		);
	const projectRoot = resolve(options.projectRoot);
	const project = config.nativeProjectDirectory;
	const auth = resolveAbsoluteMobileAuthManifest(projectRoot, config);
	const devices = resolveAbsoluteDeviceCapabilityPlan(projectRoot, 'expo');
	const syncEnabled = Boolean(auth && projectUsesAbsoluteSync(projectRoot));
	const syncSchema = syncEnabled
		? { components: discoverAbsoluteSyncSchema(projectRoot).components }
		: undefined;
	const routeModules = Object.entries(config.expoNativeRoutes);
	const moduleChecks = await Promise.all(
		routeModules.map(async ([route, module]) => ({
			exists: await exists(module),
			module,
			route
		}))
	);
	const missing = moduleChecks.find((entry) => !entry.exists);
	if (missing) {
		throw new TypeError(
			`Expo native route ${missing.route} references missing module ${missing.module}.`
		);
	}
	const marker = join(project, EXPO_PROJECT_MARKER);
	if ((await exists(project)) && !(await exists(marker))) {
		const entries = await readdir(project);
		if (entries.length > 0 && !options.force) {
			throw new TypeError(
				`Expo project directory ${project} is not AbsoluteJS-managed; rerun with --force only after reviewing it.`
			);
		}
	}
	await mkdir(project, { recursive: true });
	await writeFile(marker, 'format=1\n');
	const authEnabled = Boolean(auth);
	const files = new Map<string, string>([
		[
			join(project, '.gitignore'),
			'.expo/\nandroid/\nios/\nnode_modules/\n'
		],
		[
			join(project, 'app.json'),
			jsonSource(expoAppConfig(config, authEnabled, syncEnabled, devices))
		],
		[join(project, 'app.config.js'), expoDynamicAppConfig],
		[
			join(project, 'package.json'),
			jsonSource(expoPackage(authEnabled, syncEnabled, devices))
		],
		[join(project, 'metro.config.js'), metroConfig(projectRoot)],
		[
			join(project, 'plugins', 'withAbsoluteDevelopmentCa.js'),
			expoDevelopmentCaPlugin
		],
		[
			join(project, 'tsconfig.json'),
			jsonSource(
				expoTsConfig(projectRoot, project, authEnabled, syncEnabled)
			)
		],
		[
			join(project, 'app', '_layout.tsx'),
			layoutSource(authEnabled, syncEnabled)
		],
		[
			join(project, 'app', '__absolute', 'native', 'index.tsx'),
			nativeDiagnosticSource
		],
		[
			join(project, 'src', 'generated', 'AbsoluteDevices.ts'),
			devicesRuntimeSource(config, devices, authEnabled)
		],
		[
			join(project, 'src', 'generated', 'AbsoluteNativeRoute.tsx'),
			nativeRouteRuntimeSource(authEnabled)
		],
		[
			join(project, 'src', 'generated', 'AbsoluteWebHost.tsx'),
			webHostSource(config, auth, syncEnabled)
		]
	]);
	if (auth) {
		files.set(
			join(project, 'src', 'generated', 'AbsoluteAuth.ts'),
			authRuntimeSource(auth, config.appId)
		);
	}
	if (syncSchema) {
		files.set(
			join(project, 'src', 'generated', 'AbsoluteSync.ts'),
			syncRuntimeSource(config, syncSchema)
		);
	}
	const webAssetsPath = join(project, 'src', 'generated', 'webAssets.ts');
	if (!(await exists(webAssetsPath))) {
		files.set(webAssetsPath, emptyWebAssetsSource);
	}
	if (!config.expoNativeRoutes['/']) {
		files.set(join(project, 'app', 'index.tsx'), webRouteSource);
	}
	files.set(join(project, 'app', '[...absolute].tsx'), catchAllRouteSource);
	const nativeRouteRuntime = join(
		project,
		'src',
		'generated',
		'AbsoluteNativeRoute.tsx'
	);
	for (const [route, module] of routeModules) {
		const wrapper =
			route === '/'
				? join(project, 'app', 'index.tsx')
				: routeFile(project, route);
		files.set(
			wrapper,
			nativeWrapperSource(wrapper, module, nativeRouteRuntime, route)
		);
	}
	const removed = await pruneStaleManagedExpoRoutes(
		project,
		new Set(
			[...files.keys()].filter((path) =>
				path.startsWith(`${join(project, 'app')}${sep}`)
			)
		)
	);
	const changes = await Promise.all(
		[...files].map(([path, source]) => writeManagedFile(path, source, true))
	);
	const changed = removed + changes.filter(Boolean).length;

	return { changed, path: project, written: [...files.keys()] };
};

const walkFiles = async (root: string, directory = root): Promise<string[]> => {
	const entries = await readdir(directory, { withFileTypes: true });
	const nested = await Promise.all(
		entries.map((entry) => {
			const path = join(directory, entry.name);
			if (entry.isDirectory()) return walkFiles(root, path);
			if (entry.isFile()) return [path];
			throw new TypeError(
				`Expo embedded bundle cannot contain a symbolic link or special file: ${path}.`
			);
		})
	);

	return nested.flat().sort();
};

const renameIfPresent = async (source: string, destination: string) => {
	try {
		await rename(source, destination);

		return true;
	} catch (error) {
		if (
			typeof error === 'object' &&
			error !== null &&
			Reflect.get(error, 'code') === 'ENOENT'
		) {
			return false;
		}
		throw error;
	}
};

const installStagedDirectory = async (staging: string, destination: string) => {
	const backup = `${destination}.previous-${crypto.randomUUID()}`;
	const moved = await renameIfPresent(destination, backup);
	try {
		await rename(staging, destination);
		if (moved) await rm(backup, { force: true, recursive: true });
	} catch (error) {
		if (moved) await rename(backup, destination);
		throw error;
	}
};

const assetModuleSource = (
	assets: AbsoluteExpoAssetEntry[],
	bundleId: string,
	manifest: AbsoluteExpoNativeDataManifest
) => `${EXPO_GENERATED_HEADER}import { Asset } from 'expo-asset';
import { Directory, File, Paths } from 'expo-file-system';

${nativeDataManifestTypeSource}
declare const require: (path: string) => number;
const BUNDLE_ID = ${JSON.stringify(bundleId)};
export const ABSOLUTE_MOBILE_MANIFEST: AbsoluteMobileManifest = ${JSON.stringify(manifest)};
const ASSETS = [
${assets.map(({ asset, path }) => `\t{ module: require(${JSON.stringify(asset)}), path: ${JSON.stringify(path)} }`).join(',\n')}
] as const;

export const materializeAbsoluteWebBundle = async () => {
	const root = new Directory(Paths.document, 'absolutejs-web', BUNDLE_ID);
	root.create({ idempotent: true, intermediates: true });
	for (const entry of ASSETS) {
		const parts = entry.path.split('/');
		const name = parts.pop();
		if (!name) throw new Error('AbsoluteJS embedded asset path is invalid.');
		const directory = new Directory(root, ...parts);
		directory.create({ idempotent: true, intermediates: true });
		const destination = new File(directory, name);
		if (destination.exists) continue;
		const asset = await Asset.fromModule(entry.module).downloadAsync();
		if (!asset.localUri) throw new Error('Expo did not materialize an embedded AbsoluteJS asset.');
		new File(asset.localUri).copy(destination);
	}

	return new File(root, 'index.html').uri;
};
`;

export const syncAbsoluteExpoWebAssets = async (
	config: NormalizedAbsoluteMobileConfig
) => {
	if (config.engine !== 'expo')
		throw new TypeError('Expo asset sync requires mobile.engine: expo.');
	const marker = join(config.nativeProjectDirectory, EXPO_PROJECT_MARKER);
	if (!(await exists(marker))) {
		throw new TypeError(
			'Expo asset sync requires an AbsoluteJS-managed Expo project. Run mobile init first.'
		);
	}
	const manifestPath = join(
		config.bundleDirectory,
		'absolute-mobile-manifest.json'
	);
	const manifest: unknown = JSON.parse(await readFile(manifestPath, 'utf8'));
	const nativeDataManifest = expoNativeDataManifest(manifest);
	const { appBuild } = nativeDataManifest;
	const files = await walkFiles(config.bundleDirectory);
	const bundleHash = createHash('sha256');
	const filesWithContents = await Promise.all(
		files.map(async (file) => ({ contents: await readFile(file), file }))
	);
	filesWithContents.forEach(({ contents, file }) => {
		bundleHash.update(
			relative(config.bundleDirectory, file).replaceAll('\\', '/')
		);
		bundleHash.update('\0');
		bundleHash.update(contents);
		bundleHash.update('\0');
	});
	const bundleId = `amexpo_${bundleHash.digest('hex')}`;
	const destination = join(
		config.nativeProjectDirectory,
		'assets',
		'absolute'
	);
	await mkdir(dirname(destination), { recursive: true });
	const staging = await mkdtemp(
		join(dirname(destination), `.${basename(destination)}.stage-`)
	);
	let assets: AbsoluteExpoAssetEntry[];
	try {
		assets = await Promise.all(
			files.map(async (source, index) => {
				const name = `${String(index).padStart(6, '0')}${EXPO_ASSET_EXTENSION}`;
				await cp(source, join(staging, name));

				return {
					asset: portableRelative(
						join(config.nativeProjectDirectory, 'src', 'generated'),
						join(destination, name)
					),
					path: relative(config.bundleDirectory, source).replaceAll(
						'\\',
						'/'
					)
				};
			})
		);
		await installStagedDirectory(staging, destination);
	} catch (error) {
		await rm(staging, { force: true, recursive: true });
		throw error;
	}
	const generated = join(
		config.nativeProjectDirectory,
		'src',
		'generated',
		'webAssets.ts'
	);
	await writeManagedFile(
		generated,
		assetModuleSource(assets, bundleId, nativeDataManifest),
		true
	);

	return { appBuild, assets: assets.length, bundleId, path: destination };
};
