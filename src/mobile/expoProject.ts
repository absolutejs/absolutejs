const writeManagedFile = async (
	path: string,
	source: string,
	force: boolean
) => {
	await mkdir(dirname(path), { recursive: true });
	if (await exists(path)) {
		const current = await readFile(path, 'utf8');
		if (current === source) return false;
		if (!force && !current.startsWith(EXPO_GENERATED_HEADER)) {
			throw new TypeError(
				`Expo project file ${path} is not AbsoluteJS-managed; rerun with --force only after reviewing it.`
			);
		}
	}
	const temporary = `${path}.${crypto.randomUUID()}.tmp`;
	await writeFile(temporary, source, { flag: 'wx' });
	await rename(temporary, path);

	return true;
};

const pruneStaleManagedExpoRoutes = async (
	project: string,
	expected: ReadonlySet<string>
) => {
	const appDirectory = join(project, 'app');
	if (!(await exists(appDirectory))) return 0;
	const files = await walkFiles(appDirectory);
	const stale = (
		await Promise.all(
			files.map(async (path) => ({
				managed:
					path.endsWith('.tsx') &&
					(await readFile(path, 'utf8')).startsWith(
						EXPO_GENERATED_HEADER
					),
				path
			}))
		)
	).filter(({ managed, path }) => managed && !expected.has(path));
	await Promise.all(stale.map(({ path }) => rm(path, { force: true })));

	return stale.length;
};

